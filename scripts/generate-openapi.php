<?php

/**
 * Generates docs/openapi.json from the live /api/v1 route list.
 *
 * Every path, method and operationId in the spec is pulled from the actual
 * registered routes, so the document can never drift from what is deployed.
 * Path placeholders ({product}, {order:code}, ...) become OpenAPI parameters
 * with integer/string schemas. Run: php scripts/generate-openapi.php
 */

use Illuminate\Contracts\Console\Kernel;
use Illuminate\Support\Str;

require __DIR__.'/../vendor/autoload.php';
$app = require __DIR__.'/../bootstrap/app.php';
$app->make(Kernel::class)->bootstrap();

$routeJson = shell_exec('php artisan route:list --json --path=api/v1');
$routes = json_decode($routeJson, true);

if (! is_array($routes)) {
    fwrite(STDERR, "Could not read the route list.\n");
    exit(1);
}

// Human-readable titles per known resource segment; unknown segments get
// title-cased as a fallback.
$titles = [
    'auth' => 'Authentication',
    'products' => 'Products',
    'categories' => 'Categories',
    'brands' => 'Brands',
    'attributes' => 'Attributes',
    'attribute-values' => 'Attribute Values',
    'colors' => 'Colors',
    'currencies' => 'Currencies',
    'customers' => 'Customers',
    'staff' => 'Staff',
    'roles' => 'Roles & Permissions',
    'permissions' => 'Roles & Permissions',
    'sellers' => 'Sellers',
    'delivery-boys' => 'Delivery Boys',
    'delivery-boys-payment-histories' => 'Delivery Boy Payments',
    'delivery-boys-collection-histories' => 'Delivery Boy Collections',
    'orders' => 'Orders',
    'refund-requests' => 'Refund Requests',
    'refund-settings' => 'Refund Settings',
    'flash-deals' => 'Flash Deals',
    'blogs' => 'Blog',
    'blog-categories' => 'Blog Categories',
    'pages' => 'Pages',
    'notes' => 'Notes',
    'uploads' => 'Media Uploads',
    'carriers' => 'Carriers',
    'carrier-ranges' => 'Carrier Ranges',
    'carrier-range-prices' => 'Carrier Range Prices',
    'pickup-points' => 'Pickup Points',
    'zones' => 'Zones',
    'states' => 'States',
    'cities' => 'Cities',
    'countries' => 'Countries',
    'coupons' => 'Coupons',
    'settings' => 'Settings',
    'taxes' => 'Taxes',
    'warranties' => 'Warranties',
    'dynamic-popups' => 'Dynamic Pop-ups',
    'custom-alerts' => 'Custom Alerts',
    'email-templates' => 'Email Templates',
    'subscribers' => 'Subscribers',
    'reports' => 'Reports',
];

$spec = [
    'openapi' => '3.0.3',
    'info' => [
        'title' => 'WowMart Admin API',
        'version' => '1.0.0',
        'description' => 'Versioned REST API for the WowMart admin panel.'
            ." Every endpoint below is generated from the live route list, so it\n"
            .'always matches what is deployed. Sign in with POST /auth/login to get'
            ." a bearer token, then send it as `Authorization: Bearer <token>`.\n\n"
            .'Generated by scripts/generate-openapi.php — do not edit by hand.',
    ],
    'servers' => [
        ['url' => 'http://127.0.0.1:8124/api/v1', 'description' => 'Local development (port 8124)'],
        ['url' => 'http://127.0.0.1:8000/api/v1', 'description' => 'Local development (port 8000)'],
    ],
    'security' => [['bearerAuth' => []]],
    'tags' => [],
    'paths' => [],
    'components' => [
        'securitySchemes' => [
            'bearerAuth' => ['type' => 'http', 'scheme' => 'bearer', 'bearerFormat' => 'Sanctum'],
        ],
        'schemas' => [
            'Error' => [
                'type' => 'object',
                'properties' => [
                    'message' => ['type' => 'string'],
                    'errors' => ['type' => 'object', 'additionalProperties' => ['type' => 'array', 'items' => ['type' => 'string']]],
                ],
            ],
        ],
    ],
];

// --- collect tags -----------------------------------------------------------

$tagSet = [];
foreach ($routes as $route) {
    $segments = explode('/', trim($route['uri'], '/')); // api, v1, resource, ...
    $tag = $segments[2] ?? 'misc';
    $tagSet[$tag] = true;
}

foreach (array_keys($tagSet) as $tag) {
    $spec['tags'][] = [
        'name' => $tag,
        'description' => $titles[$tag] ?? Str::title(str_replace('-', ' ', $tag)),
    ];
}

// --- build paths ------------------------------------------------------------

foreach ($routes as $route) {
    // route:list reports index/show routes as "GET|HEAD"; keep the real verb.
    $routeVerbs = array_values(array_filter(
        explode('|', strtoupper($route['method'])),
        fn (string $verb): bool => ! in_array($verb, ['HEAD', 'OPTIONS'], true),
    ));
    if ($routeVerbs === []) {
        continue;
    }
    $method = strtolower($routeVerbs[0]);

    $path = '/'.preg_replace('#^api/v1/#', '', $route['uri']);

    // OpenAPI path parameters: {order:code} -> {code}, {product} -> {product}.
    $names = [];
    $path = preg_replace_callback('/\{([a-zA-Z_]+)(?::[a-zA-Z]+)?\}/', function ($m) use (&$names) {
        $names[] = $m[1];

        return '{'.$m[1].'}';
    }, $path);

    $segments = explode('/', trim($route['uri'], '/'));
    $tag = $segments[2] ?? 'misc';

    $nameParts = explode('.', $route['name']);
    $action = end($nameParts);
    $noun = str_replace('-', ' ', implode(' ', array_slice($nameParts, 2, -1)));

    // Route names are unique, so an id built from the full name is unique too.
    $operationId = Str::camel(str_replace(['.', '-'], ' ', preg_replace('/^api\.v1\./', '', $route['name'])));

    // Sensible one-line summaries per action.
    $summary = match ($action) {
        'index' => "List {$noun}",
        'store' => "Create {$noun}",
        'show' => "Show {$noun}",
        'update' => "Update {$noun}",
        'destroy' => "Delete {$noun}",
        'flags' => "Toggle {$noun} flags",
        'duplicate' => "Duplicate {$noun}",
        'delivery-status' => 'Update order delivery status',
        'payment-status' => 'Update order payment status',
        'status' => 'Update refund request status',
        'verification' => 'Update seller verification',
        'send' => 'Send the newsletter',
        'test-mail' => 'Send a test e-mail',
        'me' => 'Show the signed-in admin',
        'login' => 'Sign in and get a bearer token',
        'logout' => 'Revoke the current token',
        'payments' => 'List delivery-boy payment histories',
        'collections' => 'List delivery-boy collection histories',
        default => Str::title(str_replace(['-', '.'], ' ', $action)),
    };

    $op = [
        'operationId' => $operationId,
        'tags' => [$tag],
        'summary' => $summary,
        'security' => $path === '/auth/login' ? [] : [['bearerAuth' => []]],
        'responses' => [
            '200' => ['description' => 'Successful response'],
            '401' => ['$ref' => '#/components/responses/Unauthenticated'],
            '403' => ['$ref' => '#/components/responses/Forbidden'],
        ],
    ];

    if ($method === 'post') {
        $op['responses']['201'] = ['description' => 'Created'];
        unset($op['responses']['200']);
    }
    if ($method === 'delete') {
        $op['responses']['204'] = ['description' => 'Deleted'];
        unset($op['responses']['200']);
    }
    if (in_array($method, ['post', 'put', 'patch'], true)) {
        $op['responses']['422'] = ['$ref' => '#/components/responses/ValidationError'];

        $schema = ['type' => 'object'];
        if ($path === '/auth/login') {
            $schema = [
                'type' => 'object',
                'required' => ['email', 'password'],
                'properties' => [
                    'email' => ['type' => 'string', 'format' => 'email', 'example' => 'admin@wowmart.test'],
                    'password' => ['type' => 'string', 'format' => 'password', 'example' => 'password'],
                ],
            ];
        }

        $op['requestBody'] = [
            'required' => true,
            'content' => ['application/json' => ['schema' => $schema]],
        ];
    }

    foreach ($names as $paramName) {
        $op['parameters'][] = [
            'name' => $paramName,
            'in' => 'path',
            'required' => true,
            'schema' => ['type' => 'string'],
        ];
    }

    $spec['paths'][$path][$method] = $op;
}

// --- shared responses -------------------------------------------------------

$spec['components']['responses'] = [
    'Unauthenticated' => [
        'description' => 'No or expired token',
        'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]],
    ],
    'Forbidden' => [
        'description' => 'Not an administrator or missing permission',
        'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]],
    ],
    'ValidationError' => [
        'description' => 'Validation failed',
        'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]],
    ],
];

$dir = __DIR__.'/../docs';
if (! is_dir($dir)) {
    mkdir($dir, 0777, true);
}

file_put_contents($dir.'/openapi.json', json_encode($spec, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

$count = count($spec['paths']);
$ops = 0;
foreach ($spec['paths'] as $methods) {
    foreach (['get', 'post', 'put', 'patch', 'delete'] as $verb) {
        if (isset($methods[$verb])) {
            $ops++;
        }
    }
}

echo "docs/openapi.json written: {$count} paths, {$ops} operations.\n";
